export function getMarketProduct(productId) {
  return productById[productId] || null;
}

export function formatMarketQuantity(productId, quantity) {
  const product = getMarketProduct(productId);
  if (!product) return `${quantity} article${quantity > 1 ? "s" : ""}`;
  return `${quantity} ${quantity > 1 ? product.pluralLabel : product.label}`;
}

export function formatMarketLexicalLabel(productId, quantity = 0) {
  const product = getMarketProduct(productId);
  const selectedQuantity = Number.isInteger(quantity) && quantity > 0 ? quantity : 0;
  if (!product) {
    if (selectedQuantity === 0) return "un article";
    return `${selectedQuantity} article${selectedQuantity > 1 ? "s" : ""}`;
  }
  if (selectedQuantity === 0) return `${product.indefiniteArticle} ${product.label}`;
  return `${selectedQuantity} ${selectedQuantity > 1 ? product.pluralLabel : product.label}`;
}

